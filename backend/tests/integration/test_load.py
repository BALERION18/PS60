class TestHashChainIntegrity:
    """LT-04 — Sequential black-box frames maintain a valid hash chain."""

    def _make_frame(self, idx: int, prev_hash: bytes, data: bytes) -> dict:
        from shared.crypto.hash_chain import compute_frame_hash, sha256
        import base64
        frame = {
            "frame_index": idx,
            "prev_hash": base64.b64encode(prev_hash).decode(),
            "data": base64.b64encode(data).decode(),
        }
        # Compute hash over the frame without the final_hash field
        import json
        frame_bytes = json.dumps(frame, sort_keys=True).encode()
        frame["frame_hash"] = base64.b64encode(compute_frame_hash(frame_bytes)).decode()
        return frame

    def test_sha256_deterministic(self):
        from shared.crypto.hash_chain import sha256 as hc_sha256
        h1 = hc_sha256(b"hello world")
        h2 = hc_sha256(b"hello world")
        assert h1 == h2

    def test_sha256_different_data(self):
        from shared.crypto.hash_chain import sha256 as hc_sha256
        assert hc_sha256(b"hello") != hc_sha256(b"world")

    def test_sha256_output_is_32_bytes(self):
        from shared.crypto.hash_chain import sha256 as hc_sha256
        assert len(hc_sha256(b"test")) == 32

    def test_compute_frame_hash_deterministic(self):
        from shared.crypto.hash_chain import compute_frame_hash
        h1 = compute_frame_hash(b"frame-data")
        h2 = compute_frame_hash(b"frame-data")
        assert h1 == h2

    def test_compute_frame_hash_unique_for_different_data(self):
        from shared.crypto.hash_chain import compute_frame_hash
        assert compute_frame_hash(b"frame-1") != compute_frame_hash(b"frame-2")

    def test_initial_prev_hash_is_deterministic(self):
        from shared.crypto.hash_chain import initial_prev_hash
        h1 = initial_prev_hash("alert-001")
        h2 = initial_prev_hash("alert-001")
        assert h1 == h2

    def test_initial_prev_hash_differs_per_alert(self):
        from shared.crypto.hash_chain import initial_prev_hash
        assert initial_prev_hash("alert-001") != initial_prev_hash("alert-002")

    def test_verify_chain_accepts_empty_frames(self):
        from shared.crypto.hash_chain import verify_chain
        valid, msg = verify_chain([])
        assert valid  # empty chain is vacuously valid



class TestEnvelopeCompressionRatio:
    """LT-05 — Compression ratio ≤50% for real 100-reading payloads."""

    def test_100_readings_compress_under_50pct(self):
        import json
        from shared.crypto.signing import generate_station_keypair, Signer
        from edge.sync_agent.envelope import build_envelope

        priv, _ = generate_station_keypair()
        signer = Signer.from_pem_bytes(priv)
        payload = {
            "readings": [
                {"sensor_id": f"maitri.energy.gen{i % 3}.fuel_pct", "value": 45.0 + i % 10,
                 "unit": "pct", "quality_flag": "NOMINAL", "timestamp_utc": "2026-01-01T00:00:00Z"}
                for i in range(100)
            ]
        }
        json_size = len(json.dumps(payload).encode())
        env = build_envelope("maitri", "SENSOR_BATCH", payload, 1, signer)
        ratio = env["compressed_size_bytes"] / json_size
        assert ratio <= 0.5, f"Compression ratio {ratio:.2%} > 50% — zstd ineffective"

    def test_single_reading_envelope_well_formed(self):
        from shared.crypto.signing import generate_station_keypair, Signer
        from edge.sync_agent.envelope import build_envelope
        priv, _ = generate_station_keypair()
        signer = Signer.from_pem_bytes(priv)
        env = build_envelope("maitri", "SENSOR_BATCH", {"readings": [{"sensor_id": "s1", "value": 1.0}]}, 1, signer)
        for f in ("station_id", "message_type", "sequence_number", "compressed_payload",
                  "signature", "timestamp_utc", "payload_size_bytes", "compressed_size_bytes"):
            assert f in env
