def _make_batch(readings, station_id="maitri"):
    return {"station_id": station_id, "batch_id": f"lt-{uuid.uuid4().hex[:8]}", "readings": readings}


class TestConcurrentIngestion:
    """LT-01 — 100 concurrent ingest tasks finish without error."""

    @pytest.mark.asyncio
    async def test_100_concurrent_ingest_tasks(self, mock_redis):
        from unittest.mock import AsyncMock, patch
        from edge.ingestion.service import IngestionService

        async def single_ingest(i: int) -> int:
            session = AsyncMock()
            session.execute = AsyncMock()
            with patch("edge.ingestion.service.get_redis", return_value=mock_redis):
                svc = IngestionService(session=session, station_id="maitri")
                return await svc.ingest(_make_batch([make_sensor_reading(value=float(i), offset_seconds=i)]))

        start = time.monotonic()
        results = await asyncio.gather(*[single_ingest(i) for i in range(100)])
        elapsed = time.monotonic() - start

        assert all(r == 1 for r in results)
        assert elapsed < 5.0, f"100 concurrent tasks took {elapsed:.2f}s > 5s"

    @pytest.mark.asyncio
    async def test_large_batch_completes_quickly(self, mock_redis):
        """1000-reading batch finishes in <500ms with mock DB."""
        from unittest.mock import AsyncMock, patch
        from edge.ingestion.service import IngestionService

        session = AsyncMock()
        session.execute = AsyncMock()
        readings = [make_sensor_reading(value=float(i), offset_seconds=i) for i in range(1000)]

        start = time.monotonic()
        with patch("edge.ingestion.service.get_redis", return_value=mock_redis):
            svc = IngestionService(session=session, station_id="maitri")
            count = await svc.ingest(_make_batch(readings))
        elapsed = time.monotonic() - start

        assert count == 1000
        assert elapsed < 0.5, f"1000-reading batch took {elapsed:.3f}s > 0.5s"


class TestAlertIdUniqueness:
    """LT-03 — 500 evaluations produce 500 unique alert IDs."""

    def test_500_evaluations_unique_ids(self):
        from shared.schemas.config import ThresholdRule
        from edge.alert_engine.evaluator import evaluate_thresholds

        rule = ThresholdRule(
            rule_id="lt-rule",
            sensor_id="maitri.energy.gen1.fuel_pct",
            metric_name="fuel_level_percent",
            condition="lt",
            threshold_value=30.0,
            severity="HIGH",
            domain="energy",
            asset_id="maitri.gen1",
            description_template="Fuel {value:.1f}% below {threshold:.1f}%",
        )
        reading = {
            "sensor_id": "maitri.energy.gen1.fuel_pct",
            "value": 10.0,
            "domain": "energy",
            "asset_id": "maitri.gen1",
        }
        # AlertCandidate.rule_id is deterministic per (sensor, condition, threshold)
        # Alert IDs are generated by the service layer, not the evaluator
        # Verify evaluator consistently produces candidates
        for _ in range(500):
            candidates = evaluate_thresholds(reading, [rule])
            assert len(candidates) == 1

    def test_generate_alert_id_500_unique(self):
        from shared.utils.alert_id import generate_alert_id
        ids = {generate_alert_id("maitri", "energy") for _ in range(500)}
        assert len(ids) == 500, f"Only {len(ids)}/500 unique IDs — collision detected"

    def test_alert_id_entropy_8_hex_chars(self):
        from shared.utils.alert_id import generate_alert_id
        aid = generate_alert_id("maitri", "energy")
        hex_part = aid.split("-")[-1]
